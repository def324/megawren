#!/bin/sh
# Installs Megawren on Linux or macOS from its GitHub release.
#
#   curl -fsSL https://raw.githubusercontent.com/def324/megawren/main/install.sh | sh
#
# Uninstall everything this script installed:
#
#   ~/.local/share/megawren/uninstall.sh
#   curl -fsSL https://raw.githubusercontent.com/def324/megawren/main/install.sh | sh -s -- --uninstall
#
# Add --purge to also sign out of MEGA and delete ~/.megawren (your saved
# login and file index). Run with --help for all options.
set -eu

repo=def324/megawren

usage() {
    cat <<'EOF'
Usage: install.sh [options]

Installs Megawren for the current user. Run again to upgrade.

Options:
  --version X.Y.Z  Install this release instead of the latest one
  --prefix DIR     Install under DIR instead of ~/.local
                   (the program goes in DIR/bin, its files in DIR/share/megawren)
  --archive FILE   Install from a downloaded release archive. FILE.sha256 must
                   sit next to it.
  --uninstall      Remove everything this script installed
  --purge          Also sign out of MEGA and delete ~/.megawren, which holds
                   your saved login and file index. Works on its own, too.
  -h, --help       Show this help

Uninstalling removes only what this script installed. It keeps ~/.megawren
unless you add --purge. If you installed with --prefix, pass the same prefix.
EOF
}

say() { printf '%s\n' "$*"; }
die() { printf 'install.sh: %s\n' "$*" >&2; exit 1; }

# Single-quotes a value for the generated uninstaller.
quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

download() {
    if command -v curl >/dev/null 2>&1; then
        curl -fsSL --proto '=https' --tlsv1.2 -o "$2" "$1"
    elif command -v wget >/dev/null 2>&1; then
        wget -q -O "$2" "$1"
    else
        die "Install curl or wget, then run this again."
    fi
}

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | cut -d' ' -f1
    else
        die "Install sha256sum or shasum, then run this again."
    fi
}

target() {
    os=$(uname -s)
    cpu=$(uname -m)
    case $os in
        Linux)
            case $cpu in
                x86_64 | amd64) echo x86_64-unknown-linux-musl ;;
                aarch64 | arm64) echo aarch64-unknown-linux-musl ;;
                *) die "There is no Megawren build for $cpu Linux. Builds exist for x86-64 and ARM64." ;;
            esac ;;
        Darwin)
            major=$(sw_vers -productVersion | cut -d. -f1)
            [ "$major" -ge 15 ] || die "Megawren needs macOS 15 or later."
            # A shell under Rosetta reports x86_64 on Apple Silicon.
            if [ "$cpu" = arm64 ] || [ "$(sysctl -n sysctl.proc_translated 2>/dev/null || echo 0)" = 1 ]; then
                echo aarch64-apple-darwin
            else
                echo x86_64-apple-darwin
            fi ;;
        *) die "Megawren runs on Linux and macOS, not $os." ;;
    esac
}

latest_version() {
    download "https://api.github.com/repos/$repo/releases/latest" "$1/latest.json"
    sed -n 's/.*"tag_name": *"v\([^"]*\)".*/\1/p' "$1/latest.json" | head -n 1
}

# Writes the uninstaller. Empty paths skip that part, which --purge uses alone.
write_uninstaller() {
    {
        say '#!/bin/sh'
        say '# Generated by Megawren'"'"'s install.sh. Removes this installation.'
        say '# Add --purge to also sign out of MEGA and delete ~/.megawren.'
        say 'set -eu'
        say "bin=$(quote "$2")"
        say "data=$(quote "$3")"
        cat <<'EOF'
purge=false
for arg in "$@"; do
    case $arg in
        --purge) purge=true ;;
        -h | --help)
            echo "Usage: uninstall.sh [--purge]"
            echo "Removes Megawren as installed by install.sh. --purge also signs out"
            echo "of MEGA and deletes ~/.megawren (saved login and file index)."
            exit 0 ;;
        *) echo "uninstall.sh: unknown option $arg" >&2; exit 2 ;;
    esac
done

if $purge; then
    state="${HOME:?}/.megawren"
    if [ -f "$state/session.enc" ]; then
        exe=
        if [ -n "$data" ] && [ -x "$data/current/bin/megawren" ]; then
            exe="$data/current/bin/megawren"
        elif command -v megawren >/dev/null 2>&1; then
            exe=$(command -v megawren)
        fi
        signed_out=false
        # Signing out may ask for the local passphrase, so it needs a terminal.
        # The subshell matters: a failed redirection on ":" exits a POSIX shell.
        if [ -n "$exe" ] && (: </dev/tty) 2>/dev/null; then
            echo "Signing out of MEGA..."
            if "$exe" logout </dev/tty; then signed_out=true; fi
        fi
        if ! $signed_out; then
            echo "Could not sign out of MEGA. The saved session may stay active." >&2
            echo "You can end it in MEGA's session settings." >&2
        fi
    fi
    if [ -e "$state" ]; then
        rm -rf -- "$state"
        echo "Removed $state"
    fi
fi

if [ -n "$bin" ] && [ -L "$bin" ]; then
    case $(readlink "$bin") in
        "$data"/*) rm -f -- "$bin"; echo "Removed $bin" ;;
    esac
fi
if [ -n "$data" ] && [ -f "$data/install-receipt" ]; then
    rm -rf -- "$data"
    echo "Removed $data"
fi
if command -v megawren >/dev/null 2>&1; then
    echo "Another megawren is still on your PATH: $(command -v megawren)"
    echo "It was installed some other way, for example with Homebrew or a package."
elif ! $purge && [ -d "${HOME:?}/.megawren" ]; then
    echo "Kept ~/.megawren. Run this again with --purge to sign out and delete it."
fi
EOF
    } >"$1"
    chmod 755 "$1"
}

uninstall() {
    data="$prefix/share/megawren"
    if [ -f "$data/install-receipt" ] && [ -x "$data/uninstall.sh" ]; then
        if $purge; then exec "$data/uninstall.sh" --purge; fi
        exec "$data/uninstall.sh"
    fi
    say "No Megawren installed by this script under $prefix."
    if $purge; then
        tmp=$(mktemp -d)
        write_uninstaller "$tmp/uninstall.sh" "" ""
        "$tmp/uninstall.sh" --purge
        rm -rf "$tmp"
    elif command -v megawren >/dev/null 2>&1; then
        say "megawren at $(command -v megawren) was installed some other way."
    fi
}

install() {
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT
    platform=$(target)
    data="$prefix/share/megawren"
    bin="$prefix/bin/megawren"
    if [ -e "$bin" ] || [ -L "$bin" ]; then
        case $(readlink "$bin" 2>/dev/null || true) in
            "$data"/*) ;;
            *) die "$bin already exists and was not installed by this script. Remove it or pass --prefix." ;;
        esac
    fi
    if [ -n "$archive" ]; then
        [ -f "$archive" ] || die "$archive does not exist."
        [ -f "$archive.sha256" ] || die "$archive.sha256 must sit next to the archive."
        name=$(basename "$archive" .tar.gz)
        case $name in
            megawren-*-"$platform") ;;
            *) die "$archive is not the $platform build." ;;
        esac
        cp "$archive" "$tmp/$name.tar.gz"
        cp "$archive.sha256" "$tmp/$name.tar.gz.sha256"
    else
        [ -n "$version" ] || version=$(latest_version "$tmp") || version=
        [ -n "$version" ] || die "Could not find the latest release. Pass --version X.Y.Z."
        name="megawren-$version-$platform"
        url="https://github.com/$repo/releases/download/v$version/$name.tar.gz"
        say "Downloading $name..."
        download "$url" "$tmp/$name.tar.gz" || die "Could not download $url"
        download "$url.sha256" "$tmp/$name.tar.gz.sha256" || die "Could not download $url.sha256"
    fi
    expected=$(cut -d' ' -f1 "$tmp/$name.tar.gz.sha256")
    [ "$(sha256 "$tmp/$name.tar.gz")" = "$expected" ] || die "Checksum mismatch for $name.tar.gz. Nothing was installed."
    tar -xzf "$tmp/$name.tar.gz" -C "$tmp"
    "$tmp/$name/bin/megawren" --version >/dev/null 2>&1 || die "The downloaded program does not run on this system."
    installed=$("$tmp/$name/bin/megawren" --version)

    mkdir -p "$data" "$prefix/bin"
    rm -rf "$data/current.new" "$data/current.old"
    mv "$tmp/$name" "$data/current.new"
    if [ -d "$data/current" ]; then mv "$data/current" "$data/current.old"; fi
    mv "$data/current.new" "$data/current"
    rm -rf "$data/current.old"
    ln -sfn "$data/current/bin/megawren" "$bin"
    {
        say "version=${installed#megawren }"
        say "platform=$platform"
        say "bin=$bin"
        say "data=$data"
    } >"$data/install-receipt"
    write_uninstaller "$data/uninstall.sh" "$bin" "$data"

    say "Installed $installed to $bin"
    case ":$PATH:" in
        *":$prefix/bin:"*) ;;
        *) say "Add $prefix/bin to your PATH, for example in ~/.profile:"
           say "  export PATH=\"$prefix/bin:\$PATH\"" ;;
    esac
    other=$(command -v megawren 2>/dev/null || true)
    if [ -n "$other" ] && [ "$other" != "$bin" ]; then
        say "Note: $other comes first on your PATH."
    fi
    say "To uninstall, run $data/uninstall.sh"
    say "Add --purge to also sign out and delete ~/.megawren."
}

main() {
    version=
    prefix="${HOME:?}/.local"
    archive=
    remove=false
    purge=false
    while [ $# -gt 0 ]; do
        case $1 in
            --version) [ $# -ge 2 ] || die "--version needs a value"; version=${2#v}; shift ;;
            --prefix) [ $# -ge 2 ] || die "--prefix needs a value"; prefix=$2; shift ;;
            --archive) [ $# -ge 2 ] || die "--archive needs a value"; archive=$2; shift ;;
            --uninstall) remove=true ;;
            --purge) purge=true ;;
            -h | --help) usage; exit 0 ;;
            *) die "Unknown option $1. Run with --help." ;;
        esac
        shift
    done
    case $prefix in
        /*) ;;
        *) prefix="$(pwd)/$prefix" ;;
    esac
    if $remove || $purge; then
        uninstall
    else
        install
    fi
}

# Everything runs from here, so a partial download cannot run half a script.
main "$@"
